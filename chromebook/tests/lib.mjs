export const PB = globalThis.PB;
const B = PB.bytes, C = PB.crypto, P = PB.protocol;

const b64url = (u8) => Buffer.from(u8).toString('base64url');
const det = (label, n) => new Uint8Array(createHash('sha256').update(label).digest()).slice(0, n);

export async function keyFromD(d) {
  const e = createECDH('prime256v1');
  e.setPrivateKey(Buffer.from(d));
  const pub = new Uint8Array(e.getPublicKey());
  const jwk = { kty: 'EC', crv: 'P-256', d: b64url(d), x: b64url(pub.slice(1, 33)), y: b64url(pub.slice(33)) };
  const priv = await crypto.subtle.importKey('jwk', jwk, { name: 'ECDH', namedCurve: 'P-256' }, false, ['deriveBits']);
  return { priv, pub };
}

// Deterministic cross-language vectors. Swift's VectorTests checks the same file.
export async function computeVectors() {
  const H = B.hex;
  const device = det('PB vec device', 16);

  const dA = det('PB vec pair A', 32), dB = det('PB vec pair B', 32);
  const A = await keyFromD(dA), K = await keyFromD(dB);
  const na = det('PB vec pair na', 16), nb = det('PB vec pair nb', 16);
  const commit = await C.commit(device, A.pub, K.pub, nb);
  const tr = C.transcript('PB-pair-v1', device, A.pub, K.pub, na, nb);
  const shared = await C.ecdh(A.priv, K.pub);
  if (!B.equal(shared, await C.ecdh(K.priv, A.pub))) throw new Error('ECDH asymmetric');
  const trust = await C.trustBytes(shared, tr);
  const tk = await C.hmacKey(trust);
  const keys = await C.sessionKeys(shared, tk, na, nb, tr);

  const dA2 = det('PB vec resume A', 32), dB2 = det('PB vec resume B', 32);
  const A2 = await keyFromD(dA2), K2 = await keyFromD(dB2);
  const na2 = det('PB vec resume na', 16), nb2 = det('PB vec resume nb', 16);
  const tr2 = C.transcript('PB-resume-v1', device, A2.pub, K2.pub, na2, nb2);
  const shared2 = await C.ecdh(A2.priv, K2.pub);
  const keys2 = await C.sessionKeys(shared2, tk, na2, nb2, tr2);

  const c2pPlain = P.controlPlain({ t: 'ping', id: 1 });
  const p2cPlain = P.controlPlain({ t: 'pong', id: 1 });
  const c2pPayload = await new C.SecureChannel(keys.c2p, keys.p2c).seal(c2pPlain);
  const p2cPayload = await new C.SecureChannel(keys.p2c, keys.c2p).seal(p2cPlain);

  return {
    version: 1,
    note: 'Generated by chromebook/tools/gen-vectors.mjs. Hex unless noted.',
    pair: {
      device: H(device), dA: H(dA), dB: H(dB), pkA: H(A.pub), pkB: H(K.pub), na: H(na), nb: H(nb),
      commit: H(commit), transcript: H(tr), sas: await C.sas(tr), shared: H(shared), trust: H(trust),
      okm: H(keys.okm), macC: H(await C.confirmMac(tk, 'C', tr)), macP: H(await C.confirmMac(tk, 'P', tr)),
    },
    resume: {
      device: H(device), trust: H(trust), dA: H(dA2), dB: H(dB2), pkA: H(A2.pub), pkB: H(K2.pub),
      na: H(na2), nb: H(nb2), transcript: H(tr2), sas: await C.sas(tr2), shared: H(shared2), okm: H(keys2.okm),
      macC: H(await C.confirmMac(tk, 'C', tr2)), macP: H(await C.confirmMac(tk, 'P', tr2)),
    },
    secure: {
      keysFrom: 'pair.okm', counter: 0,
      c2pPlain: H(c2pPlain), c2pPayload: H(c2pPayload),
      p2cPlain: H(p2cPlain), p2cPayload: H(p2cPayload),
      c2pFramed: H(P.frame(c2pPayload)),
    },
  };
}

// In-memory duplex link that delivers writes in small random-sized chunks.
export function linkPair(maxChunk = 23) {
  const mk = () => new EventTarget();
  const a = mk(), b = mk();
  const wire = (from, to) => {
    from.write = async (u8) => {
      const copy = u8.slice();
      for (let o = 0; o < copy.length;) {
        const n = 1 + Math.floor(Math.random() * maxChunk);
        const piece = copy.subarray(o, o + n);
        o += n;
        await Promise.resolve();
        to.dispatchEvent(new CustomEvent('data', { detail: piece }));
      }
    };
  };
  wire(a, b); wire(b, a);
  return [a, b];
}

export function memStore() {
  let trust = null;
  const id = B.random(16);
  return {
    async getDeviceId() { return id; },
    async loadTrust() { return trust ? { ...trust.meta, key: await C.hmacKey(trust.raw) } : null; },
    async saveTrust(raw, meta) { trust = { raw: raw.slice(), meta }; },
    async clearTrust() { trust = null; },
    get raw() { return trust && trust.raw; },
  };
}

export function once(target, type) {
  return new Promise((resolve) => target.addEventListener(type, (e) => resolve(e.detail), { once: true }));
}

