const det = (label, n) => new Uint8Array(createHash('sha256').update(label).digest()).slice(0, n);

// X25519 private key from a fixed 32-byte scalar (pre-clamping), for deterministic vectors.
export async function x25519Key(d) {
  const der = Buffer.concat([Buffer.from('302e020100300506032b656e04220420', 'hex'), Buffer.from(d)]);
  createPrivateKey({ key: der, format: 'der', type: 'pkcs8' }); // validates
  return crypto.subtle.importKey('pkcs8', der, { name: 'X25519' }, false, ['deriveBits']);
}

// Deterministic cross-language vectors. Swift's VectorTests and tools/xcheck.py check the same file.
export async function computeVectors() {
  const H = B.hex;
  const { P: p, int2le } = C._field;

  const map = [];
  for (const r of [0n, 1n, 2n, 3n, p - 1n, (1n << 254n) + 12345n, BigInt('0x' + H(det('PB vec map', 32))) % p]) {
    map.push({ r: H(int2le(r)), u: H(int2le(C.elligator2(r))) });
  }

  const passwords = ['correct horse battery staple', 'pw', 'pässwörd', 'k7mq-3xph'];
  const generators = [];
  for (const pw of passwords) generators.push({ password: pw, G: H(await C.generator(pw)) });

  const password = 'correct horse battery staple';
  const G = await C.generator(password);
  const device = det('PB2 vec device', 16);
  const da = det('PB2 vec ya', 32), db = det('PB2 vec yb', 32);
  const ka = await x25519Key(da), kb = await x25519Key(db);
  const Ya = await C.x25519(ka, G), Yb = await C.x25519(kb, G);
  const na = det('PB2 vec na', 16), nb = det('PB2 vec nb', 16);
  const K = await C.x25519(ka, Yb);
  if (!B.equal(K, await C.x25519(kb, Ya))) throw new Error('CPace asymmetric');
  const tr = C.transcript(device, Ya, Yb, na, nb);
  const keys = await C.deriveKeys(K, tr);

  const c2pPlain = P.controlPlain({ t: 'ping', id: 1 });
  const p2cPlain = P.encodeTunnel(P.T_DATA, 7, B.utf8('hello body'));
  const c2pPayload = await new C.SecureChannel(keys.c2p, keys.p2c).seal(c2pPlain);
  const p2cPayload = await new C.SecureChannel(keys.p2c, keys.c2p).seal(p2cPlain);

  return {
    version: 3,
    note: 'Generated by chromebook/tools/gen-vectors.mjs. Hex unless noted. Scalars are raw X25519 private keys (clamped on use).',
    elligator2: map,
    generators,
    handshake: {
      password, G: H(G), device: H(device), ya: H(da), yb: H(db), Ya: H(Ya), Yb: H(Yb), na: H(na), nb: H(nb),
      K: H(K), transcript: H(tr), okm: H(keys.okm),
      macP: H(await C.macP(keys, tr)), macC: H(await C.macC(keys, tr)),
    },
    secure: {
      counter: 0, c2pPlain: H(c2pPlain), c2pPayload: H(c2pPayload), p2cPlain: H(p2cPlain), p2cPayload: H(p2cPayload),
      c2pFramed: H(P.frame(c2pPayload)),
    },
    tunnel: [
      { op: 'CONNECT', frame: H(P.encodeTunnel(P.T_CONNECT, 1, P.connectPayload('example.com', 443))) },
      { op: 'OPENED', frame: H(P.encodeTunnel(P.T_OPENED, 1)) },
      { op: 'DATA', frame: H(P.encodeTunnel(P.T_DATA, 0xabcdef01, Uint8Array.of(0x16, 0x03, 0x01))) },
      { op: 'CLOSE', frame: H(P.encodeTunnel(P.T_CLOSE, 2, Uint8Array.of(P.R_DNS))) },
    ],
  };
}

// In-memory duplex link that delivers writes in small random-sized chunks.
export function linkPair(maxChunk = 23) {
  const a = new EventTarget(), b = new EventTarget();
  const wire = (from, to) => {
    from.write = async (u8) => {
      const copy = u8.slice();
      for (let o = 0; o < copy.length;) {
        const n = 1 + Math.floor(Math.random() * maxChunk);
        const piece = copy.subarray(o, o + n);
        o += n;
        await Promise.resolve();
        to.dispatchEvent(new CustomEvent('data', { detail: piece }));
      }
    };
  };
  wire(a, b); wire(b, a);
  return [a, b];
}

export function once(target, type) {
  return new Promise((resolve) => target.addEventListener(type, (e) => resolve(e.detail), { once: true }));
}

// Node "internet" for the mock iPhone: real TCP via net, with a host → local port map.
// Unknown hosts fail as DNS errors unless allowRealNet.
import net from 'node:net';
export const openSockets = new Set();
export function netConnector(hosts = {}, { allowRealNet = false } = {}) {
  return (host, port, cb) => {
    const R = PB.protocol;
    const mapped = hosts[`${host}:${port}`] ?? hosts[host];
    if (mapped === undefined && !allowRealNet) { setTimeout(() => cb.closed(R.R_DNS), 0); return { write() {}, close() {} }; }
    if (mapped === 'refuse') { setTimeout(() => cb.closed(R.R_REFUSED), 0); return { write() {}, close() {} }; }
    const s = mapped === undefined ? net.connect(port, host) : net.connect(mapped, '127.0.0.1');
    let done = false;
    openSockets.add(s);
    s.on('close', () => openSockets.delete(s));
    s.on('connect', () => cb.opened());
    s.on('data', (d) => cb.data(new Uint8Array(d)));
    s.on('end', () => { if (!done) { done = true; cb.closed(R.R_NORMAL); } });
    s.on('error', (e) => { if (!done) { done = true; cb.closed(e.code === 'ECONNREFUSED' ? R.R_REFUSED : e.code === 'ENOTFOUND' ? R.R_DNS : R.R_RESET); } });
    s.on('close', () => { if (!done) { done = true; cb.closed(R.R_NORMAL); } });
    return { write: (u8) => s.write(u8), close: () => { done = true; s.destroy(); } };
  };
}

export async function connect({ password = 'test-pass', phonePassword = 'test-pass', phoneOpts = {} } = {}) {
  const [cLink, pLink] = linkPair();
  const phone = new MockPhone(pLink, { password: phonePassword, ...phoneOpts });
  const s = new PB.Session({ link: cLink, deviceId: B.random(16), deviceName: 'Test CB', G: await C.generator(password) });
  return { s, phone, cLink, pLink };
}
